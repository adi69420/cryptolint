# ======================================================================
# SHAPE 4 -- attribute assignment (the commonest production form)
# ======================================================================

# [HIGH] a session with verification switched off for every request it makes
def build_session():
    s = requests.Session()
    s.verify = False
    return s


# [HIGH] on a module-level session object
def disable_on_module_session():
    session.verify = False


# [REVIEW] unconfirmable value on the attribute form
def session_from_flag(flag):
    s = requests.Session()
    s.verify = flag
    return s


# [silent] explicit True on the attribute form
def session_verified():
    s = requests.Session()
    s.verify = True
    return s


# [REVIEW] a VARIABLE holding a CA path. My first label said silent -- that was
# wrong: the tool cannot tell a variable holding "/etc/ca.pem" from one holding
# False, so the stated rule (variable -> unconfirmable) makes this REVIEW.
def session_custom_ca():
    s = requests.Session()
    s.verify = CA_BUNDLE_PATH
    return s


# [silent] a string literal CA path
def session_literal_ca():
    s = requests.Session()
    s.verify = "/etc/ca.pem"
    return s


# ======================================================================
# SHAPE 5 -- kwargs unpacking
# ======================================================================

# [HIGH] a LITERAL dict is readable, so it is read
def fetch_literal_kwargs(url):
    return requests.get(url, **{"verify": False})


# [silent] a VARIABLE dict cannot be read -- disclosed in LIMITS, not flagged
def fetch_variable_kwargs(url, config):
    return requests.get(url, **config)


CA_BUNDLE_PATH = "/etc/ssl/certs/ca.pem"
