# [silent] alias -- r2 is not tracked, and rng stops being tracked
def aliased():
    rng = np.random.default_rng()
    r2 = rng
    key = r2.bytes(16)
    return key


# [silent] stored on an attribute -- not tracked
class Holder:
    def setup(self):
        rng = np.random.default_rng()
        self.rng = rng

    def use_later(self):
        token = self.rng.bytes(16)
        return token


# [silent] passed as an argument -- tracking ends
def passed_away(sink):
    rng = np.random.default_rng()
    sink(rng)
    secret = rng.bytes(16)
    return secret


