import secrets

import numpy as np

CHARS = "abcdefghijklmnopqrstuvwxyz"


# ======================================================================
# HIGH -- a strong signal on some axis
# ======================================================================

# [HIGH] high-precision target name
def issue_credential():
    token = random.randint(0, 999999)
    return token


# [HIGH] high-precision target name
def make_login():
    password = random.choice(CHARS)
    return password


# [HIGH] high-precision ENCLOSING FUNCTION name, no target name at all
def generate_secret():
    return random.random()


