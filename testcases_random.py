# [silent] a probability
def coin_flip():
    probability = random.random()
    return probability > 0.5


# [silent] sampling an index
def pick(items):
    idx = random.randint(0, len(items) - 1)
    return items[idx]


# [silent] shuffling a non-secret list
def reorder(playlist):
    random.shuffle(playlist)
    return playlist


# ======================================================================
